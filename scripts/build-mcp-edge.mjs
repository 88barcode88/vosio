import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve, dirname, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import ts from "typescript";
import console from "node:console";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "supabase/functions/vosio-mcp/generated");
const seen = new Map();
const packages = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8")).dependencies;

// Package the exact reachable TypeScript graph, retaining types for the independent Deno check.
function emit(sourcePath) {
  const name = relative(resolve(root, "src"), sourcePath).split(sep).join("/");
  if (name.startsWith("../") || !name.endsWith(".ts")) throw new Error("Edge graph escaped src or reached a non-TS module");
  if (seen.has(name)) return;
  const original = readFileSync(sourcePath, "utf8");
  seen.set(name, createHash("sha256").update(original).digest("hex"));
  let source = name === "lib/env.server.ts" ? 'export { getEdgeAdminEnv as getSupabaseAdminEnv } from "./mcp/config.server";\n' : original;
  const parsed = ts.createSourceFile(sourcePath, source, ts.ScriptTarget.Latest, true);
  const changes = [];
  // Reject unsupported dynamic dependencies instead of shipping an incomplete deployment graph.
  function visit(node) {
    if (ts.isCallExpression(node) && (node.expression.kind === ts.SyntaxKind.ImportKeyword || ts.isIdentifier(node.expression) && node.expression.text === "require")) throw new Error(`Dynamic dependency in ${name}`);
    const specifier = (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) ? node.moduleSpecifier : ts.isImportTypeNode(node) && ts.isLiteralTypeNode(node.argument) ? node.argument.literal : undefined;
    if (specifier && ts.isStringLiteral(specifier)) {
      const spec = specifier.text;
      if (spec === "server-only") { changes.push([node.getStart(parsed), node.end, ""]); return; }
      if (spec.startsWith("next") || spec === "react") throw new Error(`Web runtime dependency reached Edge: ${name}: ${spec}`);
      if (spec.startsWith(".") || spec.startsWith("@/")) {
        let target = spec.startsWith("@/") ? resolve(root, "src", spec.slice(2)) : resolve(dirname(sourcePath), spec);
        if (!target.endsWith(".ts")) target += ".ts";
        if (!existsSync(target)) throw new Error(`Missing dependency: ${name}: ${spec}`);
        let path = relative(dirname(sourcePath), target).split(sep).join("/");
        if (!path.startsWith(".")) path = `./${path}`;
        changes.push([specifier.getStart(parsed), specifier.end, JSON.stringify(path)]);
        emit(target);
      } else if (!spec.startsWith("node:")) {
        const pkg = spec.startsWith("@") ? spec.split("/").slice(0, 2).join("/") : spec.split("/")[0];
        if (!packages[pkg] || !/^\d+\.\d+\.\d+$/.test(packages[pkg])) throw new Error(`Unpinned Edge dependency: ${spec}`);
        changes.push([specifier.getStart(parsed), specifier.end, JSON.stringify(`npm:${pkg}@${packages[pkg]}${spec.slice(pkg.length)}`)]);
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(parsed);
  for (const [start, end, value] of changes.sort((a, b) => b[0] - a[0])) source = source.slice(0, start) + value + source.slice(end);
  const target = resolve(output, name); mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, `// Generated by scripts/build-mcp-edge.mjs; edit the original src file.\n${source}`);
}
emit(resolve(root, "src/lib/mcp/edge-handler.server.ts"));
writeFileSync(resolve(output, "manifest.json"), JSON.stringify(Object.fromEntries([...seen].sort()), null, 2) + "\n");
console.log(`Packaged ${seen.size} source modules for vosio-mcp.`);
