import { createHash, createPrivateKey, createPublicKey } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, posix, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import console from "node:console";
import process from "node:process";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "extension");
const sourceSrc = resolve(source, "src");
const targets = ["chrome", "edge", "dev"];
const target = process.argv[2] ?? "chrome";
if (!targets.includes(target)) throw new Error(`Unknown target "${target}". Use one of: ${targets.join(", ")}`);
const output = resolve(root, ".tmp/extension", target);
const CONTENT_ENTRIES = ["content/entry-meet.ts", "content/entry-teams.ts", "content/entry-zoom.ts", "content/entry-custom.ts"];

// Lists all files below a directory recursively.
function walk(directory) {
  return readdirSync(directory).flatMap((name) => {
    const path = join(directory, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

// Returns the path of a source file relative to extension/src with forward slashes.
function rel(path) {
  return relative(sourceSrc, path).split(sep).join("/");
}

// Transpiles one TypeScript file to the given module format; ./x.ts imports are rewritten to ./x.js.
function transpile(path, module) {
  const result = ts.transpileModule(readFileSync(path, "utf8"), {
    fileName: path,
    reportDiagnostics: true,
    compilerOptions: { target: ts.ScriptTarget.ES2022, module, rewriteRelativeImportExtensions: true, removeComments: false }
  });
  if (result.diagnostics?.length) throw new Error(`${rel(path)}: ${result.diagnostics.map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n")).join("; ")}`);
  return result.outputText;
}

// Bundles a content script entry and its relative imports into one classic script (content scripts cannot use ES modules).
function bundleClassic(entryPath) {
  const modules = new Map();
  // Collects a module and its dependencies, recording resolved dependency ids per require specifier.
  function collect(path) {
    const id = rel(path).replace(/\.ts$/, ".js");
    if (modules.has(id)) return id;
    const code = transpile(path, ts.ModuleKind.CommonJS);
    const deps = {};
    modules.set(id, { code, deps });
    for (const match of code.matchAll(/require\("(\.[^"]+)"\)/g)) {
      const depPath = resolve(dirname(path), match[1].replace(/\.js$/, ".ts"));
      deps[match[1]] = collect(depPath);
    }
    return id;
  }
  const entry = collect(entryPath);
  const defs = [...modules].map(([id, { code, deps }]) => `${JSON.stringify(id)}: [function (exports, require) {\n${code}\n}, ${JSON.stringify(deps)}]`).join(",\n");
  return `// Generated by scripts/build-vosio-extension.mjs; edit extension/src instead.\n(function () {\nconst defs = {\n${defs}\n};\nconst cache = {};\nfunction load(id) {\n  if (cache[id]) return cache[id].exports;\n  const module = { exports: {} };\n  cache[id] = module;\n  const [fn, deps] = defs[id];\n  fn.call(null, module.exports, (spec) => load(deps[spec]));\n  return module.exports;\n}\nload(${JSON.stringify(entry)});\n})();\n`;
}

// Derives the manifest "key" (public key) and the resulting extension id from an optional untracked private key file.
function devKey() {
  const keyFile = process.env.VOSIO_EXTENSION_DEV_KEY_FILE ?? resolve(source, "dev-key.pem");
  if (!existsSync(keyFile)) return null;
  const der = createPublicKey(createPrivateKey(readFileSync(keyFile))).export({ type: "spki", format: "der" });
  const id = [...createHash("sha256").update(der).digest().subarray(0, 16)].map((byte) => String.fromCharCode(97 + (byte >> 4)) + String.fromCharCode(97 + (byte & 15))).join("");
  return { key: der.toString("base64"), id };
}

rmSync(output, { recursive: true, force: true });
mkdirSync(output, { recursive: true });

let count = 0;
for (const file of walk(sourceSrc)) {
  const path = rel(file);
  if (file.endsWith(".d.ts")) continue;
  if (file.endsWith(".ts")) {
    if (CONTENT_ENTRIES.includes(path)) continue;
    // Content modules are inlined into their entry bundles and are not emitted separately.
    if (path.startsWith("content/")) continue;
    const destination = resolve(output, path.replace(/\.ts$/, ".js"));
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, transpile(file, ts.ModuleKind.ESNext));
    count += 1;
  } else {
    const destination = resolve(output, path);
    mkdirSync(dirname(destination), { recursive: true });
    cpSync(file, destination);
  }
}
for (const entry of CONTENT_ENTRIES) {
  const destination = resolve(output, entry.replace(/\.ts$/, ".js"));
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, bundleClassic(resolve(sourceSrc, entry)));
  count += 1;
}
cpSync(resolve(source, "icons"), resolve(output, "icons"), { recursive: true });

const manifest = JSON.parse(readFileSync(resolve(source, "manifest.json"), "utf8"));
if (target === "dev") {
  manifest.name = `${manifest.name} (dev)`;
  const key = devKey();
  if (key) {
    manifest.key = key.key;
    console.log(`Dev key found: extension id will be ${key.id}`);
  } else {
    console.warn("No dev key (extension/dev-key.pem): the unpacked extension id will change per machine. See extension/README.md.");
  }
}
writeFileSync(resolve(output, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

// Verify that every file referenced by the manifest exists in the output.
const referenced = [
  manifest.background.service_worker, manifest.action.default_popup, manifest.options_ui.page,
  ...Object.values(manifest.icons), ...manifest.content_scripts.flatMap((script) => script.js)
];
for (const file of referenced) {
  if (!existsSync(resolve(output, posix.normalize(file)))) throw new Error(`Manifest references missing file: ${file}`);
}
console.log(`Built Vosio extension (${target}): ${count} scripts -> ${relative(root, output)}`);
